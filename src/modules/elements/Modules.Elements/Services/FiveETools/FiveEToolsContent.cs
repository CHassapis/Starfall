using System.Text.Json.Nodes;
using System.Xml.Linq;
using Microsoft.Extensions.Logging;
using Starlights.Modules.Elements.Integration;

namespace Starlights.Modules.Elements.Services.FiveETools;

/// <summary>
/// Translates what the 5etools data has and Aurora Legacy (with its pull requests and homebrew) does not into Aurora
/// elements: spells, feats, class options (invocations, metamagic, …), backgrounds, species, subclasses and classes.
/// Aurora's content always wins: anything Aurora has under the same name, from any book, is left alone. What 5etools
/// records as data becomes rules (proficiencies, choices, ability scores, spell slots, spells always prepared,
/// prerequisites); what it only describes in words stays words. Everything is generated in a fixed order with ids
/// made from the book and the name, so an update re-creates only what really changed.
/// </summary>
internal sealed partial class FiveEToolsContent
{
    /// <summary>Said at the end of every generated description.</summary>
    public const string Footer = "Imported automatically from 5etools.";

    private readonly FiveEToolsJson _json;
    private readonly FiveEToolsAuroraIndex _aurora;
    private readonly Dictionary<string, (string Name, DateTime? Published)> _books;
    private readonly ILogger _logger;
    private readonly List<XElement> _generated = [];
    private readonly Dictionary<string, List<(string Id, string Source, bool Modern)>> _generatedByName = new(StringComparer.Ordinal);
    private readonly Dictionary<string, int> _counts = new(StringComparer.Ordinal);
    private readonly Dictionary<string, string> _sourceNames;
    private readonly List<ImportDiagnostic>? _diagnostics;

    public FiveEToolsContent(FiveEToolsJson json, FiveEToolsAuroraIndex aurora, IReadOnlyDictionary<string, (string Name, DateTime? Published)> books, ILogger logger,
        List<ImportDiagnostic>? diagnostics = null)
    {
        _json = json;
        _aurora = aurora;
        _books = new Dictionary<string, (string, DateTime?)>(books, StringComparer.OrdinalIgnoreCase);
        _logger = logger;
        _diagnostics = diagnostics;
        _sourceNames = aurora.Sources.GroupBy(NormalizeBook).ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
    }

    /// <summary>How many of each kind were generated by the last <see cref="Generate"/>.</summary>
    public IReadOnlyDictionary<string, int> Counts => _counts;

    public XDocument Generate()
    {
        Spells();
        Feats();
        OptionalFeatures();
        Backgrounds();
        Species();
        Classes();
        Subclasses();

        _logger.LogInformation("generated from 5etools what Aurora lacks: {Counts}",
            string.Join(", ", _counts.OrderBy(c => c.Key, StringComparer.Ordinal).Select(c => $"{c.Value} {c.Key}")));
        return new XDocument(new XElement("elements", _generated));
    }

    /// <summary>Something the data refers to and does not have, so part of an entry (or all of it) is left out.</summary>
    private void Report(ImportDiagnosticCode code, string message, string? elementId, string elementName, string detail) =>
        _diagnostics?.Add(new ImportDiagnostic(ImportDiagnosticSeverity.Warning, code, ImportDiagnosticImporter.FiveETools, message)
        {
            File = FiveEToolsData.Prefix + "content.xml",
            ElementId = elementId,
            ElementName = elementName,
            Detail = detail,
        });

    // ---- which entries count ----

    /// <summary>Unearthed Arcana and Plane Shift (left out of the Aurora import too), and what the data marks as not for players.</summary>
    private bool Skip(JsonObject entry)
    {
        var source = FiveEToolsJson.Str(entry, "source") ?? "";
        if (source.StartsWith("UA", StringComparison.OrdinalIgnoreCase) || source.StartsWith("PS", StringComparison.Ordinal)
            || BookName(source).StartsWith("Plane Shift", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }
        return entry["reprintedAs"] is not null || FiveEToolsJson.Bool(entry, "isSidekick") || FiveEToolsJson.Bool(entry, "isReprinted")
            || entry["traitTags"] is JsonArray tags && tags.Any(t => t?.ToString() == "NPC Race");
    }

    /// <summary>
    /// Whether Aurora has this entry: by name in any book, by a similar name in the same book, or (for a copy of
    /// another entry with a few edits, 5etools' way of writing variants) has the entry it copies.
    /// </summary>
    private bool AuroraHas(string family, JsonObject entry, params string[] otherNames)
    {
        var name = FiveEToolsJson.Str(entry, "name") ?? "";
        if (_aurora.Has(family, [name, .. otherNames]) || _aurora.HasSimilar(family, name, SourceName(FiveEToolsJson.Str(entry, "source") ?? "")))
        {
            return true;
        }
        return FiveEToolsJson.Str(entry, "_copiedFrom")?.Split('|')[0] is { Length: > 0 } copied && _aurora.Has(family, copied);
    }

    /// <summary>A 2024-rules entry: marked "one" edition, or from a book published after the 2024 Player's Handbook.</summary>
    private bool IsModern(JsonObject entry)
    {
        var edition = FiveEToolsJson.Str(entry, "edition");
        if (edition is not null)
        {
            return edition == "one";
        }
        var source = FiveEToolsJson.Str(entry, "source") ?? "";
        return source == "XPHB" || _books.TryGetValue(source, out var book) && book.Published >= new DateTime(2024, 9, 1);
    }

    private string BookName(string abbreviation) => _books.TryGetValue(abbreviation, out var book) ? book.Name : abbreviation;

    // a 5etools book that Aurora also has keeps Aurora's spelling of the name, so the books merge
    private string SourceName(string abbreviation)
    {
        var name = BookName(abbreviation);
        return _sourceNames.GetValueOrDefault(NormalizeBook(name), name);
    }

    private static string NormalizeBook(string name) =>
        name.Replace('’', '\'').Replace(" (2014)", "", StringComparison.Ordinal).Trim().ToLowerInvariant();

    // ---- building elements ----

    private static string Slug(string text) =>
        string.Join('_', new string(text.ToUpperInvariant().Select(c => char.IsAsciiLetterOrDigit(c) ? c : '_').ToArray())
            .Split('_', StringSplitOptions.RemoveEmptyEntries));

    private static string IdOf(string kind, string source, params string[] names) =>
        $"ID_5ETOOLS_{kind}_{Slug(source)}_{string.Join('_', names.Select(Slug))}";

    /// <summary>A new element, remembered under its name so later elements can grant it.</summary>
    private XElement NewElement(string kind, string name, string type, string source, string id, bool modern, XElement? description = null)
    {
        var element = new XElement("element",
            new XAttribute("name", name),
            new XAttribute("type", type),
            new XAttribute("source", SourceName(source)),
            new XAttribute("id", id));
        if (description is not null)
        {
            element.Add(description);
        }
        _generated.Add(element);
        _counts[kind] = _counts.GetValueOrDefault(kind) + 1;
        var key = $"{type}\u0001{FiveEToolsAuroraIndex.Words(name)}";
        _generatedByName.TryAdd(key, []);
        _generatedByName[key].Add((id, SourceName(source), modern));
        return element;
    }

    /// <summary>The description: the entries, with references to class and subclass features written out, and the footer.</summary>
    private XElement Description(JsonNode? entries, params JsonNode?[] more)
    {
        var description = new XElement("description");
        foreach (var part in new[] { entries }.Concat(more))
        {
            if (part is not null)
            {
                description.Add(FiveEToolsRenderer.Entries(FiveEToolsJson.Element(ResolveReferences(part.DeepClone()))));
            }
        }
        description.Add(new XElement("p", new XElement("em", Footer)));
        return description;
    }

    /// <summary>The words for the character sheet: the entries as plain text.</summary>
    private static XElement Sheet(XElement description, string? alt = null)
    {
        var text = string.Join(" ", description.Elements().Where(e => e.Name != "h5" && e.Value != Footer).Select(e => e.Value.Trim()).Where(t => t.Length > 0));
        var sheet = new XElement("sheet", new XElement("description", text));
        if (alt is not null)
        {
            sheet.Add(new XAttribute("alt", alt));
        }
        return sheet;
    }

    /// <summary>An Aurora element, or one generated earlier, of this type and name: the book's own first, then the edition's.</summary>
    private string? Find(string type, string name, string? source = null, bool? modern = null)
    {
        var book = source is null ? null : SourceName(source);
        if (_aurora.Find(type, name, book, modern).FirstOrDefault() is { } aurora)
        {
            return aurora.Id;
        }
        return _generatedByName.GetValueOrDefault($"{type}\u0001{FiveEToolsAuroraIndex.Words(name)}")?
            .OrderByDescending(g => g.Source == book).ThenByDescending(g => modern is { } m && g.Modern == m).Select(g => g.Id).FirstOrDefault();
    }

    /// <summary>"fireball|xphb" or "fireball#c" (a 5etools spell reference) as a spell id.</summary>
    private string? SpellId(string reference, bool modern)
    {
        var parts = reference.Split('#')[0].Split('|');
        var source = parts.Length > 1 && parts[1].Length > 0 ? parts[1].ToUpperInvariant() : null;
        return Find("Spell", parts[0], source, source is null ? modern : null);
    }

    private static XElement Grant(string type, string id, int level = 0, string? requirements = null)
    {
        var grant = new XElement("grant", new XAttribute("type", type), new XAttribute("id", id));
        if (level > 1)
        {
            grant.Add(new XAttribute("level", level));
        }
        if (requirements is not null)
        {
            grant.Add(new XAttribute("requirements", requirements));
        }
        return grant;
    }

    private static XElement Select(string type, string name, string? supports, int number = 1, int level = 0, string? requirements = null)
    {
        var select = new XElement("select", new XAttribute("type", type), new XAttribute("name", name));
        if (!string.IsNullOrEmpty(supports))
        {
            select.Add(new XAttribute("supports", supports));
        }
        if (number > 1)
        {
            select.Add(new XAttribute("number", number));
        }
        if (level > 1)
        {
            select.Add(new XAttribute("level", level));
        }
        if (requirements is not null)
        {
            select.Add(new XAttribute("requirements", requirements));
        }
        return select;
    }

    private static XElement Stat(string name, string value, int level = 0, string? bonus = null)
    {
        var stat = new XElement("stat", new XAttribute("name", name), new XAttribute("value", value));
        if (bonus is not null)
        {
            stat.Add(new XAttribute("bonus", bonus));
        }
        if (level > 1)
        {
            stat.Add(new XAttribute("level", level));
        }
        return stat;
    }

    private static XElement RulesOf(XElement element)
    {
        if (element.Element("rules") is { } rules)
        {
            return rules;
        }
        element.Add(rules = new XElement("rules"));
        return rules;
    }

    /// <summary>Drops an empty rules block, so a description-only element looks like Aurora's.</summary>
    private static void Tidy(XElement element)
    {
        if (element.Element("rules") is { HasElements: false } rules)
        {
            rules.Remove();
        }
    }

    // ---- references inside entries ----

    private Dictionary<string, JsonObject>? _featureIndex;

    /// <summary>Class, subclass and option features by their 5etools reference ("Name|Class|SRC|Level", …).</summary>
    private Dictionary<string, JsonObject> FeatureIndex()
    {
        if (_featureIndex is not null)
        {
            return _featureIndex;
        }
        _featureIndex = new(StringComparer.OrdinalIgnoreCase);
        foreach (var feature in _json.Load("class/class-*.json", "classFeature"))
        {
            _featureIndex.TryAdd($"cf|{FeatureKey(feature)}", feature);
        }
        foreach (var feature in _json.Load("class/class-*.json", "subclassFeature"))
        {
            _featureIndex.TryAdd($"scf|{SubclassFeatureKey(feature)}", feature);
        }
        foreach (var option in _json.Load("optionalfeatures.json", "optionalfeature"))
        {
            _featureIndex.TryAdd($"of|{FiveEToolsJson.Str(option, "name")}|{FiveEToolsJson.Str(option, "source")}", option);
        }
        return _featureIndex;
    }

    private static string FeatureKey(JsonObject f) =>
        $"{FiveEToolsJson.Str(f, "name")}|{FiveEToolsJson.Str(f, "className")}|{FiveEToolsJson.Str(f, "classSource")}|{FiveEToolsJson.Int(f, "level")}";

    private static string SubclassFeatureKey(JsonObject f) =>
        $"{FiveEToolsJson.Str(f, "name")}|{FiveEToolsJson.Str(f, "className")}|{FiveEToolsJson.Str(f, "classSource")}|{FiveEToolsJson.Str(f, "subclassShortName")}|{FiveEToolsJson.Str(f, "subclassSource")}|{FiveEToolsJson.Int(f, "level")}";

    // a reference's parts with the defaults 5etools leaves out ("Name|Class||3" means the PHB)
    private static string NormalizeReference(string reference, int sourceIndex)
    {
        var parts = reference.Split('|').ToList();
        for (var i = 0; i < parts.Count; i++)
        {
            if (parts[i].Length == 0 && (i == 2 || i == sourceIndex))
            {
                parts[i] = "PHB";
            }
        }
        return string.Join('|', parts);
    }

    private JsonObject? ClassFeature(string reference) => FeatureIndex().GetValueOrDefault($"cf|{NormalizeReference(reference, 2)}");

    private JsonObject? SubclassFeature(string reference) => FeatureIndex().GetValueOrDefault($"scf|{NormalizeReference(reference, 4)}");

    /// <summary>Writes referenced features out as named sections, so the description holds their text.</summary>
    private JsonNode? ResolveReferences(JsonNode? node, int depth = 0)
    {
        switch (node)
        {
            case JsonArray array:
                return new JsonArray(array.Select(i => ResolveReferences(i?.DeepClone(), depth)).ToArray());
            case JsonObject obj:
                var type = FiveEToolsJson.Str(obj, "type");
                JsonObject? referenced = type switch
                {
                    "refClassFeature" => FiveEToolsJson.Str(obj, "classFeature") is { } r ? ClassFeature(r) : null,
                    "refSubclassFeature" => FiveEToolsJson.Str(obj, "subclassFeature") is { } r ? SubclassFeature(r) : null,
                    "refOptionalfeature" => FiveEToolsJson.Str(obj, "optionalfeature") is { } r
                        ? FeatureIndex().GetValueOrDefault($"of|{r.Split('|')[0]}|{(r.Split('|').ElementAtOrDefault(1) is { Length: > 0 } s ? s : "PHB")}")
                        : null,
                    _ => null,
                };
                if (type is "refClassFeature" or "refSubclassFeature" or "refOptionalfeature")
                {
                    if (referenced is null || depth > 4)
                    {
                        return null;
                    }
                    return new JsonObject
                    {
                        ["type"] = "entries",
                        ["name"] = FiveEToolsJson.Str(referenced, "name"),
                        ["entries"] = ResolveReferences(referenced["entries"]?.DeepClone(), depth + 1),
                    };
                }
                var copy = new JsonObject();
                foreach (var (key, value) in obj)
                {
                    copy[key] = key is "entries" or "items" ? ResolveReferences(value?.DeepClone(), depth) : value?.DeepClone();
                }
                return copy;
            default:
                return node;
        }
    }
}
