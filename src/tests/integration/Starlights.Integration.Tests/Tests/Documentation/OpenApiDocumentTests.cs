using System.Text.Json;
using System.Text.Json.Nodes;
using AwesomeAssertions;

namespace Starlights.Integration.Tests.Documentation;

/// <summary>
/// docs/api/openapi.json is the API description published in the repository. It is generated from the running
/// endpoints here, so it cannot drift from them: the test fails when the endpoints changed and the file did not.
/// Regenerate it with STARLIGHTS_UPDATE_OPENAPI=1 (see docs/api/README.md).
/// </summary>
[TestClass]
public sealed class OpenApiDocumentTests : IntegrationTestBase
{
    private IntegrationHost _integration = default!;

    [TestInitialize]
    public void Initialize() => _integration = IntegrationHost.CreateDefaultBuilder(this).Build();

    [TestCleanup]
    public void Cleanup() => _integration.Dispose();

    private static string RepositoryFile(string relative)
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            if (File.Exists(Path.Combine(dir.FullName, "Starlights.slnx")))
            {
                return Path.Combine(dir.FullName, relative);
            }
        }
        throw new InvalidOperationException("Can't find the repository root (Starlights.slnx).");
    }

    /// <summary>The generated document as published: no servers (each installation has its own address).</summary>
    private async Task<string> Generate()
    {
        using var api = _integration.CreateClient();
        var document = JsonNode.Parse(await api.GetStringAsync("/openapi/v1.json"))!.AsObject();
        document.Remove("servers");
        return document.ToJsonString(new JsonSerializerOptions { WriteIndented = true }).ReplaceLineEndings("\n") + "\n";
    }

    [TestMethod]
    [Timeout(TestConstants.Timeout, CooperativeCancellation = true)]
    public async Task ThePublishedOpenApiDocument_MatchesTheEndpoints()
    {
        var generated = await Generate();
        var path = RepositoryFile(Path.Combine("docs", "api", "openapi.json"));
        if (Environment.GetEnvironmentVariable("STARLIGHTS_UPDATE_OPENAPI") == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            await File.WriteAllTextAsync(path, generated, TestContext.CancellationToken);
        }

        File.Exists(path).Should().BeTrue("docs/api/openapi.json is generated by running this test with STARLIGHTS_UPDATE_OPENAPI=1");
        (await File.ReadAllTextAsync(path, TestContext.CancellationToken)).ReplaceLineEndings("\n").Should().Be(generated,
            "the endpoints changed: regenerate docs/api/openapi.json with STARLIGHTS_UPDATE_OPENAPI=1");
    }

    [TestMethod]
    [Timeout(TestConstants.Timeout, CooperativeCancellation = true)]
    public async Task TheDocument_DescribesTheInventoryWithItsCustomAttacks()
    {
        var document = JsonNode.Parse(await Generate())!;

        document["paths"]!["/api/characters/{characterId}/inventory"]!["get"].Should().NotBeNull();
        document["components"]!["schemas"]!["CharacterInventory"]!["properties"]!["customAttacks"].Should().NotBeNull();
        document["components"]!["schemas"]!["CustomAttack"]!["properties"]!["toHit"].Should().NotBeNull();
    }

    [TestMethod]
    [Timeout(TestConstants.Timeout, CooperativeCancellation = true)]
    public async Task ClassesNamedAlikeInTwoModules_AreDescribedSeparately()
    {
        var document = JsonNode.Parse(await Generate())!;
        JsonNode Response(string path) =>
            document["components"]!["schemas"]![document["paths"]![path]!["get"]!["responses"]!["200"]!["content"]!["application/json"]!["schema"]!["$ref"]!.GetValue<string>().Split('/')[^1]]!;

        // the characters' ability scores (with their calculated modifiers), not the content administration's list
        Response("/api/characters/{characterId}/ability-scores")["properties"]!["abilityScores"].Should().NotBeNull();
        Response("/api/elements/ability-scores")["properties"]!["items"].Should().NotBeNull();
        document["components"]!["schemas"]!["AbilityScoreDataModel"]!["properties"]!["calculatedModifier"].Should().NotBeNull();
    }
}
